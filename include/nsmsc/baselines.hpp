#pragma once

#include "nsmsc/objective_oracle.hpp"
#include "nsmsc/solution.hpp"

#include <cstddef>
#include <cstdint>
#include <span>

namespace nsmsc {
[[nodiscard]] Solution fGreedyLocalSearch(
    ObjectiveOracle& oracle, std::size_t budget, double epsilon = 0.1);

// Runs the same improving-exchange local search from an external seed order.
[[nodiscard]] Solution localSearchFromOrder(
    ObjectiveOracle& oracle,
    std::span<const ElementId> order,
    std::size_t budget,
    double epsilon = 0.1,
    std::uint64_t maxExchangeEvaluations = 10'000'000,
    double maxSeconds = 60.0);

// Lu and Yang (2024), Algorithm 1, on a normalized monotone objective.
[[nodiscard]] Solution thresholdGreedyOnTotal(
    ObjectiveOracle& oracle, std::size_t budget, double epsilon = 0.1);

// Exact marginal greedy on the full, potentially non-submodular objective F.
[[nodiscard]] Solution greedyOnTotal(
    ObjectiveOracle& oracle,
    std::size_t budget);

// Uniform random subset generated by shuffling with a reproducible seed.
[[nodiscard]] Solution randomSelection(
    ObjectiveOracle& oracle,
    std::size_t budget,
    std::uint64_t seed);

// Residual Random Greedy for a uniform matroid (cardinality constraint).
[[nodiscard]] Solution residualRandomGreedy(
    ObjectiveOracle& oracle,
    std::size_t budget,
    std::uint64_t seed);

// Li et al. (2022), Fast Threshold Greedy Algorithms 1 and 2.
[[nodiscard]] Solution fastThresholdGreedyOnTotal(
    ObjectiveOracle& oracle,
    std::size_t budget,
    double epsilon = 0.1,
    double alpha = 1.0);

}  // namespace nsmsc
